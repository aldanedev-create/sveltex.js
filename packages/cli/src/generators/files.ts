import type { GeneratorKind } from './types.js';
import { usageError } from '../terminal/errors.js';
import { safeRelativePath } from '../safety/paths.js';

const SEGMENT = /^[A-Za-z][A-Za-z0-9_-]*$/;

export function validateArtifactName(name: string): string {
  safeRelativePath(name);
  for (const segment of name.split('/')) {
    if (!SEGMENT.test(segment)) {
      throw usageError(`Invalid name "${name}": each path segment must start with a letter and contain only letters, digits, "_" or "-".`, 'SX_CLI_INVALID_NAME');
    }
  }
  return name;
}

function pascalCase(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter((part) => part !== '')
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('');
}

function camelCase(name: string): string {
  const pascal = pascalCase(name);
  return pascal[0]!.toLowerCase() + pascal.slice(1);
}

export interface GeneratedFile {
  readonly relativePath: string;
  readonly content: string;
}

export interface GenerateOptions {
  readonly kind: GeneratorKind;
  readonly name: string;
}

export const GENERATOR_KINDS: readonly GeneratorKind[] = Object.freeze([
  'module', 'service', 'middleware', 'route', 'component', 'test',
]);

export function isGeneratorKind(value: string): value is GeneratorKind {
  return (GENERATOR_KINDS as readonly string[]).includes(value);
}

/** Produce a single conventional, compiling source file. Never overwrites existing files. */
export function generateFile(options: GenerateOptions): GeneratedFile {
  const name = validateArtifactName(options.name);
  const pascal = pascalCase(name);
  const camel = camelCase(name);

  switch (options.kind) {
    case 'module':
      return Object.freeze({
        relativePath: `src/lib/server/modules/${name}.ts`,
        content: `import { defineModule, token } from '@sveltex/core';

export interface ${pascal}Service {
  readonly describe: () => string;
}

export const ${camel}Token = token<${pascal}Service>('${name}');

export const ${camel}Module = defineModule({
  name: '${name}',
  providers: [
    {
      provide: ${camel}Token,
      useValue: { describe: () => '${pascal} service' } satisfies ${pascal}Service,
    },
  ],
  exports: [${camel}Token],
});
`,
      });

    case 'service':
      return Object.freeze({
        relativePath: `src/lib/server/services/${name}.ts`,
        content: `import { token } from '@sveltex/core';

export class ${pascal}Service {
  describe(): string {
    return '${pascal} service';
  }
}

export const ${camel}Token = token<${pascal}Service>('${name}.service');
`,
      });

    case 'middleware':
      return Object.freeze({
        relativePath: `src/lib/server/middleware/${name}.ts`,
        content: `import type { Handle } from '@sveltejs/kit';

/** Compose this with SvelteKit sequence() alongside createSvelteXHandler(app). */
export function create${pascal}Handle(): Handle {
  return async ({ event, resolve }) => {
    // Add request-scoped logic here; never replace the SvelteX handle.
    return resolve(event);
  };
}
`,
      });

    case 'route':
      return Object.freeze({
        relativePath: `src/routes/${name}/+server.ts`,
        content: `import { json } from '@sveltejs/kit';
import type { RequestHandler } from './$types';

export const GET: RequestHandler = async () => json({ name: '${name}', ok: true });
`,
      });

    case 'component':
      return Object.freeze({
        relativePath: `src/lib/components/${pascal}.svelte`,
        content: `<script lang="ts">
  interface Props {
    title?: string;
  }

  let { title = '${pascal}' }: Props = $props();
</script>

<section class="${camel}">
  <h2>{title}</h2>
  <p>Generated by the sveltex CLI. Edit this component freely.</p>
</section>

<style>
  .${camel} {
    padding: 1rem;
    border: 1px solid currentColor;
    border-radius: 0.5rem;
  }
</style>
`,
      });

    case 'test':
      return Object.freeze({
        relativePath: `tests/${name}.test.mjs`,
        content: `import test from 'node:test';
import assert from 'node:assert/strict';

test('${name}: behaviour is defined', () => {
  assert.equal(typeof '${name}', 'string');
});
`,
      });
  }
}
